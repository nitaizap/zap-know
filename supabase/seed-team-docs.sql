- פרמטרים יושבים במערך `event_params`, ושולפים אותם עם `UNNEST`.

## שאילתות בסיס
### משתמשים ואירועים לפי יום
```sql
select event_date, count(distinct user_pseudo_id) users, count(*) events
from `project.analytics_XXXX.events_*`
where _table_suffix between '20261001' and '20261019'
group by 1 order by 1;
```

### פניות (generate_lead) לפי מקור
```sql
select traffic_source.source, traffic_source.medium, count(*) leads
from `project.analytics_XXXX.events_*`
where event_name = 'generate_lead'
  and _table_suffix >= format_date('%Y%m%d', date_sub(current_date(), interval 28 day))
group by 1, 2 order by 3 desc;
```

### שליפת פרמטר מאירוע
```sql
select (select value.string_value from unnest(event_params) where key = 'page_location') page
from `project.analytics_XXXX.events_*`
where event_name = 'page_view' limit 100;
```

